// Build Waypoint Desk into dist/ (or --out): copy the page, the pinned runtime (hash-checked), render the
// manifest and network for the Conform origin and the partner URL, then build and check the network with
// the agentify-website skill's build_network.mjs (vendored, no Python).
//   CONFORM_PUBLIC_ORIGIN=https://conform.example DEMO_PARTNER_URL=https://partner.example/net node scripts/build.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rr = path.resolve(here, "../../packages/reference-runtime");
const args = process.argv.slice(2);
const outArg = args.indexOf("--out");
const out = path.resolve(outArg >= 0 ? args[outArg + 1] : path.join(here, "dist"));
const check = args.includes("--check");
const conform = (process.env.CONFORM_PUBLIC_ORIGIN ?? "http://127.0.0.1:8787").replace(/\/$/, "");
const partnerUrl = process.env.DEMO_PARTNER_URL ?? "http://localhost:8091/tidewhistle_guesthouse";
const partnerOrigin = new URL(partnerUrl).origin;
const partnerPage = new URL("./", partnerUrl).href;
if (new URL(conform).origin !== conform) throw new Error(`CONFORM_PUBLIC_ORIGIN must be an origin, not ${conform}`);

for (const line of (await readFile(path.join(rr, "HASHES.sha256"), "utf8")).trim().split("\n")) {
  const [hash, file] = line.split(/\s+/);
  if (createHash("sha256").update(await readFile(path.join(rr, file))).digest("hex") !== hash) throw new Error(`Runtime file changed: ${file}`);
}
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await cp(path.join(here, "site"), out, { recursive: true });
await cp(path.join(rr, "runtime"), path.join(out, "runtime"), { recursive: true });
const fill = (t) => t.replaceAll("{{CONFORM_ORIGIN}}", conform).replaceAll("{{PARTNER_URL}}", partnerUrl).replaceAll("{{PARTNER_ORIGIN}}", partnerOrigin);
await writeFile(path.join(out, "agent-manifest.json"), fill(await readFile(path.join(here, "agent/agent-manifest.template.json"), "utf8")));
await writeFile(path.join(out, "waypoint_desk.hocon"), fill(await readFile(path.join(here, "agent/waypoint_desk.template.hocon"), "utf8")));
await writeFile(path.join(out, "links.json"), `${JSON.stringify({ version: 1, networks: { waypoint_desk: {} } }, null, 2)}\n`);
const partners = [{ name: "Tidewhistle Guesthouse", offers: "A seaside guesthouse: rooms, prices, house policies and bookings.", networkUrl: partnerUrl, page: partnerPage }];
await writeFile(path.join(out, "desk-data.js"), `// Generated by scripts/build.mjs.\nexport const PARTNERS = ${JSON.stringify(partners, null, 2)};\n`);
execFileSync(process.execPath, [path.join(rr, "skill/scripts/build_network.mjs"), path.join(out, "waypoint_desk.hocon"), "--manifest", path.join(out, "agent-manifest.json"), "--runtime", path.join(rr, "runtime"), ...(check ? ["--check"] : [])], { stdio: "inherit" });
console.log(`Waypoint Desk built in ${out} (Conform ${conform}, partner ${partnerUrl}).`);
